    public string? GioiTinh;
    public int Tuoi;



    // Gioi thieu ban than - HANH DONG
    public void GioiThieu(){
        Console.WriteLine($"Xin chao, toi ten la {Ten}, gioi tinh {GioiTinh}, toi {Tuoi} tuoi");
    }

}




